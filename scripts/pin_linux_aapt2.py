#!/usr/bin/env python3
"""Pin the Google Maven AAPT2 Linux artifact without disabling Gradle verification.

Upstream DSHA build190 metadata pins aapt2 Windows only. Google Maven Linux
binary checksum independently appears in multiple projects' metadata. The
canonical version, group, Windows SHA and Linux SHA are all exact, fail-closed.
This is a scoped supplement, never Gradle --dependency-verification off.
"""
from pathlib import Path
import argparse
import hashlib
import re
import xml.etree.ElementTree as ET

VERSION = "9.1.1-14792394"
WINDOWS_SHA = "e27e3c895bfb9698c956d5e35c514570a0f084874c081d95a690181a606dbe10"
LINUX_SHA = "e7ae17af6e4093c771243e82d66462353de87befaac206bfb43e557ac1c34440"
OLD = f'''      <component group="com.android.tools.build" name="aapt2" version="{VERSION}">
         <artifact name="aapt2-{VERSION}-windows.jar">
            <sha256 value="{WINDOWS_SHA}" origin="Generated by Gradle"/>
         </artifact>
         <artifact name="aapt2-{VERSION}.pom">'''
NEW = f'''      <component group="com.android.tools.build" name="aapt2" version="{VERSION}">
         <artifact name="aapt2-{VERSION}-linux.jar">
            <sha256 value="{LINUX_SHA}" origin="Reviewed from multiple independent public Gradle verification records"/>
         </artifact>
         <artifact name="aapt2-{VERSION}-windows.jar">
            <sha256 value="{WINDOWS_SHA}" origin="Generated by Gradle"/>
         </artifact>
         <artifact name="aapt2-{VERSION}.pom">'''


def patch(content: str) -> str:
    # The upstream XML must match its published Windows artifact record.
    if content.count(OLD) != 1:
        raise ValueError("STOP: unexpected upstream AAPT2 verification metadata")
    if f'aapt2-{VERSION}-linux.jar' in content:
        raise ValueError("STOP: Linux AAPT2 record already exists")
    updated = content.replace(OLD, NEW, 1)
    root = ET.fromstring(updated)
    ns = {"v": "https://schema.gradle.org/dependency-verification"}
    comps = root.findall(f'.//v:component[@group="com.android.tools.build"][@name="aapt2"][@version="{VERSION}"]', ns)
    if len(comps) != 1:
        raise ValueError("STOP: expected one pinned AAPT2 component")
    a = comps[0].find(f'v:artifact[@name="aapt2-{VERSION}-linux.jar"]', ns)
    if a is None or len(a) != 1 or a[0].attrib.get("value") != LINUX_SHA:
        raise ValueError("STOP: invalid Linux AAPT2 pin")
    return updated


def main():
    p = argparse.ArgumentParser()
    p.add_argument("source_root", type=Path)
    args = p.parse_args()
    file = args.source_root / "gradle" / "verification-metadata.xml"
    before = file.read_text(encoding="utf-8")
    after = patch(before)
    file.write_text(after, encoding="utf-8", newline="")
    print("AAPT2 Linux pin: OK")
    print("Google Maven group: com.android.tools.build:aapt2:" + VERSION)
    print("SHA-256: " + LINUX_SHA)
    print("metadata sha256: " + hashlib.sha256(after.encode()).hexdigest())


if __name__ == "__main__":
    main()
